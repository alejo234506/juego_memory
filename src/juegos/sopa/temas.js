/** Lista de { texto, definicion } de un tema (acepta también palabras sueltas). */
export function entradasDe(idTema) {
  return TEMAS[idTema].palabras.map((p) =>
    Array.isArray(p) ? { texto: p[0], definicion: p[1] } : typeof p === 'string' ? { texto: p, definicion: '' } : p
  );
}
